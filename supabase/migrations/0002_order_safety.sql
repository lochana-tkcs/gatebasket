-- Order safety fixes:
--   1. Idempotent place_order: retrying with the same client id never creates a second order.
--   2. Lock products in a fixed order so two carts can't deadlock each other.
--   3. Auto-cancel orders the store hasn't accepted within 15 minutes (and restock them).
--   4. Stream product changes over Realtime so stock updates appear live.
--   5. in_stock is now only the owner's switch; restocking never overrides it.
--      A product is available when in_stock and (stock_qty is null or stock_qty > 0).

-- ───────────────────────── Columns ─────────────────────────

alter table public.orders
  add column client_order_id uuid,
  add column cancel_reason text check (cancel_reason in ('resident', 'store_timeout')),
  add constraint orders_resident_client_order_key unique (resident_id, client_order_id);

-- Existing rows: items that were switched off only because their count hit zero are owner-on again.
update public.products set in_stock = true where stock_qty = 0 and not in_stock;

-- ───────────────────────── place_order ─────────────────────────

drop function public.place_order(jsonb, public.payment_mode, text);

-- Place an order atomically. p_items: [{"product_id": uuid, "qty": int}, ...]
-- p_client_id is generated by the app once per checkout; retries with the same id return the same order.
create function public.place_order(
  p_items jsonb,
  p_payment_mode public.payment_mode,
  p_note text default null,
  p_client_id uuid default null
)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_profile profiles%rowtype;
  v_store stores%rowtype;
  v_order uuid;
  v_subtotal numeric(10, 2) := 0;
  v_item record;
  v_product products%rowtype;
begin
  select * into v_profile from profiles where id = auth.uid();
  if v_profile.id is null or v_profile.society_id is null or v_profile.flat_id is null then
    raise exception 'Join your society before ordering';
  end if;

  if p_client_id is not null then
    select id into v_order from orders where resident_id = v_profile.id and client_order_id = p_client_id;
    if v_order is not null then
      return v_order;
    end if;
  end if;

  select * into v_store from stores where society_id = v_profile.society_id;
  if v_store.id is null then
    raise exception 'Your society has no store yet';
  end if;
  if not v_store.is_open then
    raise exception 'The store is closed right now';
  end if;

  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  begin
    insert into orders (store_id, resident_id, flat_id, subtotal, delivery_fee, total, payment_mode, note, client_order_id)
    values (v_store.id, v_profile.id, v_profile.flat_id, 0, v_store.delivery_fee, 0, p_payment_mode,
            nullif(trim(p_note), ''), p_client_id)
    returning id into v_order;
  exception when unique_violation then
    -- A concurrent retry with the same client id got there first.
    select id into v_order from orders where resident_id = v_profile.id and client_order_id = p_client_id;
    return v_order;
  end;

  for v_item in
    select (e ->> 'product_id')::uuid as product_id, sum((e ->> 'qty')::int)::int as qty
    from jsonb_array_elements(p_items) e
    group by 1
    -- Always lock rows in id order, so overlapping carts queue instead of deadlocking.
    order by 1
  loop
    if v_item.qty <= 0 then
      raise exception 'Invalid quantity';
    end if;

    -- Lock the row so two orders can't oversell the same stock.
    select * into v_product from products where id = v_item.product_id and store_id = v_store.id for update;
    if v_product.id is null then
      raise exception 'A product in your cart is no longer available';
    end if;
    if not v_product.in_stock or v_product.stock_qty = 0 then
      raise exception '% is out of stock', v_product.name;
    end if;
    if v_product.stock_qty is not null then
      if v_product.stock_qty < v_item.qty then
        raise exception 'Only % left of %', v_product.stock_qty, v_product.name;
      end if;
      update products set stock_qty = stock_qty - v_item.qty where id = v_product.id;
    end if;

    insert into order_items (order_id, product_id, name_snapshot, price_snapshot, qty)
    values (v_order, v_product.id, v_product.name, v_product.price, v_item.qty);
    v_subtotal := v_subtotal + v_product.price * v_item.qty;
  end loop;

  if v_subtotal < v_store.min_order then
    raise exception 'Minimum order is ₹%', v_store.min_order;
  end if;

  update orders
     set subtotal = v_subtotal, total = v_subtotal + v_store.delivery_fee
   where id = v_order;

  return v_order;
end;
$$;

-- ───────────────────────── Restock ─────────────────────────

-- Put tracked stock back. Leaves in_stock alone, so an owner's manual "out of stock" sticks.
create or replace function public.restock_order(p_order uuid) returns void
language sql security definer set search_path = public as $$
  update products p
     set stock_qty = p.stock_qty + oi.qty
    from order_items oi
   where oi.order_id = p_order and oi.product_id = p.id and p.stock_qty is not null
$$;
revoke execute on function public.restock_order(uuid) from public, anon, authenticated;

create or replace function public.cancel_order(p_order uuid) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_order orders%rowtype;
begin
  select * into v_order from orders where id = p_order for update;
  if v_order.id is null or v_order.resident_id <> auth.uid() then
    raise exception 'Order not found';
  end if;
  if v_order.status <> 'placed' then
    raise exception 'The store has already accepted this order';
  end if;

  update orders set status = 'cancelled', cancel_reason = 'resident', closed_at = now() where id = p_order;
  perform restock_order(p_order);
end;
$$;

-- ───────────────────────── Auto-cancel ─────────────────────────

-- Cancel orders still waiting for the store after p_minutes, and put their stock back.
-- Runs every minute via pg_cron (scheduled below); returns how many orders it cancelled.
create function public.expire_stale_orders(p_minutes int default 15) returns int
language plpgsql security definer set search_path = public as $$
declare
  v_order uuid;
  v_count int := 0;
begin
  for v_order in
    select id from orders
     where status = 'placed' and created_at < now() - make_interval(mins => p_minutes)
     order by created_at
     for update skip locked
  loop
    update orders set status = 'cancelled', cancel_reason = 'store_timeout', closed_at = now() where id = v_order;
    perform restock_order(v_order);
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;
revoke execute on function public.expire_stale_orders(int) from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    perform cron.schedule('expire-stale-orders', '* * * * *', 'select public.expire_stale_orders()');
  end if;
end;
$$;

